"""Write firmware/gas_monitor/ca_certs.h: the root certificates the ESP32 trusts when talking to Supabase.
Supabase sits behind Cloudflare, which issues certificates from Let's Encrypt (ISRG roots) or
Google Trust Services (GTS roots), so both families are included.
Run from the repo root:  python tools/make_ca_certs.py   (needs: pip install certifi)
Check the result against your project with:  python tools/check_supabase.py"""
import re
from pathlib import Path

import certifi

ROOTS = ["ISRG Root X1", "ISRG Root X2", "GTS Root R1", "GTS Root R4"]

bundle = Path(certifi.where()).read_text(encoding="utf-8")
pems = []
for label in ROOTS:
    m = re.search(r'# Label: "%s"\n.*?(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)' % re.escape(label),
                  bundle, re.S)
    assert m, "root not found in certifi bundle: " + label
    pems.append("// " + label + "\n" + m.group(1))

root = Path(__file__).resolve().parent.parent
out = root / "firmware" / "gas_monitor" / "ca_certs.h"
out.write_text(
    "// GENERATED by tools/make_ca_certs.py from the Mozilla root store (certifi).\n"
    "// Root CAs for *.supabase.co: " + ", ".join(ROOTS) + "\n"
    "#pragma once\n"
    'const char SUPABASE_ROOT_CA[] = R"pem(\n' + "\n".join(pems) + '\n)pem";\n',
    encoding="utf-8", newline="\n")
# plain PEM copy for tools/check_supabase.py
(root / "tools" / "ca_certs.pem").write_text("\n".join(p.split("\n", 1)[1] for p in pems) + "\n", encoding="utf-8")
print("wrote", out)
